# ── DATACLASS ─────────────────────────────────────────────────────────────────

@dataclass
class WrappedPrompt:
    original_prompt : str
    label           : str
    vulnerability   : str
    main_system     : str
    verify_system   : str
    main_model      : str = MAIN_MODEL
    verifier_model  : str = VERIFIER_MODEL


# ── WRAP FUNCTION ─────────────────────────────────────────────────────────────

def wrap_prompt(prompt: str, label: str) -> WrappedPrompt:
    """
    Builds a WrappedPrompt containing system prompts for both the
    main LLM call and the verifier call.

    Args:
        prompt : Sanitized prompt string
        label  : CCS label from classifier e.g. "ccs4", "benign"

    Returns:
        WrappedPrompt dataclass
    """
    if label not in WRAPPERS:
        raise ValueError(
            f"Unknown label '{label}'. Expected one of: {list(WRAPPERS.keys())}"
        )

    wrapper = WRAPPERS[label]

    return WrappedPrompt(
        original_prompt = prompt,
        label           = label,
        vulnerability   = wrapper["name"],
        main_system     = wrapper["main_system"],
        verify_system   = wrapper["verify_system"],
    )


def build_wrapped_prompt(prompt: str, classification_result: dict) -> WrappedPrompt:
    """
    Convenience function that accepts the classifier output dict directly.

    Args:
        prompt                : Sanitized prompt string
        classification_result : Output dict from CCSClassifier.classify()
    """
    label = classification_result["label"]
    if label == "uncertain":
        label = "benign"

    return wrap_prompt(prompt, label)