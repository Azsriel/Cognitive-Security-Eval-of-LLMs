def load_csv(path: str) -> pd.DataFrame:
    """Try UTF-8 first, fall back to Windows-1252."""
    try:
        return pd.read_csv(path, encoding="utf-8")
    except UnicodeDecodeError:
        return pd.read_csv(path, encoding="windows-1252")
    
def parse_verdict(response: str) -> tuple[str, str]:
    """
    Extracts verdict and reasoning from VERDICT: <word> format.

    Returns:
        (verdict, reasoning) tuple
    """
    lines     = response.strip().splitlines()
    verdict   = "UNKNOWN"
    reasoning = ""

    for i, line in enumerate(lines):
        match = re.match(r"VERDICT\s*:\s*(PASS|WARN|FAIL)", line.strip().upper())
        if match:
            verdict   = match.group(1)
            reasoning = "\n".join(lines[i+1:]).strip(" :\n-")
            break

    # Fallback — scan anywhere in response if format wasn't followed
    if verdict == "UNKNOWN":
        match = re.search(r"\b(PASS|WARN|FAIL)\b", response.upper())
        if match:
            verdict   = match.group(1)
            reasoning = response.strip()

    return verdict, reasoning

def run_verifier(
    input_csv        : str,
    output_csv       : str,
    label_col        : str = "label",
    response_col     : str = "main_response",
    prompt_col       : str = "prompt"
) -> pd.DataFrame:
    df = load_csv(input_csv)

    # Validate required columns
    required = {label_col, response_col, prompt_col}
    missing  = required - set(df.columns)
    if missing:
        raise ValueError(f"Input CSV is missing required columns: {missing}")

    # Normalize label column
    df[label_col] = df[label_col].str.strip().str.lower()

    print(f"Loaded {len(df)} rows from {input_csv}")
    print(f"Running secondary verifier on column: '{response_col}'\n")

    verdicts = []
    reasonings = []

    for i, row in df.iterrows():
        label         = row[label_col]
        response_text = str(row[response_col])
        prompt = str(row[prompt_col])
        system_prompt = SECONDARY_VERIFY_SYSTEMS.get(label, SECONDARY_VERIFY_SYSTEMS["benign"])

        raw = call_llm(
            system_prompt = system_prompt,
            user_message  = "Original Prompt: \n" + prompt + "Response: \n" + response_text + "\n" + system_prompt,   # only the response to audit
            model         = VERIFIER_MODEL,
            history       = None             # no history needed
        )

        verdict, reasoning = parse_verdict(raw)
        verdicts.append(verdict)
        reasonings.append(reasoning)

        # Progress indicator
        print(f"  [{i+1:>4}/{len(df)}] {label:<8} → {verdict}")
        
    df["secondary_verdict"] = verdicts
    df["secondary_reasoning"] = reasonings

    # ── SAVE ──────────────────────────────────────────────────────────────────
    df.to_csv(output_csv, index=False, encoding="utf-8")
    print(f"\nSecondary verification complete.")
    print(f"Results saved to: {output_csv}")

    # ── QUICK SUMMARY ─────────────────────────────────────────────────────────
    print("\n── Secondary Verdict Summary ──\n")
    print(f"{'Label':<8} {'Vulnerability':<26} {'Total':>6} {'PASS':>6} {'WARN':>6} {'FAIL':>6} {'UNKNOWN':>8}")
    print("─" * 72)

    for label in df[label_col].unique():
        subset  = df[df[label_col] == label]
        counts  = subset["secondary_verdict"].value_counts()
        print(
            f"{label:<8} "
            f"{LABEL_NAMES.get(label, 'Unknown'):<26} "
            f"{len(subset):>6} "
            f"{counts.get('PASS',    0):>6} "
            f"{counts.get('WARN',    0):>6} "
            f"{counts.get('FAIL',    0):>6} "
            f"{counts.get('UNKNOWN', 0):>8}"
        )

    print("─" * 72)
    total_counts = df["secondary_verdict"].value_counts()
    print(
        f"{'ALL':<8} {'Combined':<26} "
        f"{len(df):>6} "
        f"{total_counts.get('PASS',    0):>6} "
        f"{total_counts.get('WARN',    0):>6} "
        f"{total_counts.get('FAIL',    0):>6} "
        f"{total_counts.get('UNKNOWN', 0):>8}"
    )

    return df


